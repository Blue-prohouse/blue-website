The question comes up in almost every meeting: should we film or animate? The answer is not a matter of taste. It is a matter of what you are trying to say.

Live action wins when you want to convince people of something that **exists**: a product you can touch, a place you can visit, real people. Animation wins when you need to explain something that **cannot be filmed**.

Here are three cases where motion graphics is the right choice, not merely the cheaper one.

## Case 1: The subject is abstract or invisible

How do you film a financial service? An insurance system? Data moving between platforms?

You can of course film an employee smiling at a screen, but the viewer learns nothing about the service. Those shots fill time without explaining.

Animation here is not decoration. It is the only way to show what cannot be seen: how money moves, how systems connect, what happens inside the black box.

**Rule:** if what you sell is an idea or a process rather than a physical thing, animation explains it faster.

## Case 2: The content changes often

A filmed ad is a final decision. Changing a price, adding a feature or rewording a line means reshooting — same actor, same lighting, same location. Usually impossible in practice.

With animation, you open the project and change the number.

If you know the content will be updated within a year — prices, figures, sign-up steps, product features — animation saves you a full reproduction.

**Rule:** changing content gets animated; fixed content gets filmed.

## Case 3: Filming is dangerous, costly or impossible

A factory that cannot be stopped for a shoot. A surgical procedure. An accident explained in a safety video. A location in another country. A product not yet manufactured.

Here the comparison is not between two qualities, but between a project that is possible and one that is not.

**Rule:** if filming means halting operations or putting someone at risk, animation is not a compromise.

## And when is filming right?

To keep this balanced: live action is stronger when you need **trust**. A real customer testimonial, a tour of your premises, a founder speaking to camera. Animation explains well, but it cannot prove a thing exists.

And in campaigns built on human empathy — a story, a moment, an expression — a real performer remains more convincing than any drawn character.

## The third option: mixing

The best work often combines both: live footage of the product and people, with a motion layer explaining the numbers and the process. That gives you the credibility of reality and the clarity of graphics in one piece.

## In short

Ask yourself: am I proving something exists, or explaining how it works? **Proof is filmed. Explanation is animated.**
