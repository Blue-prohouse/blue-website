The most expensive mistake in social video is a simple one: shooting one piece in one ratio, then trying to crop it later for every platform. The result is cropped heads and text outside the frame.

The fix is not shooting each ratio separately. It is **shooting with the ratios in mind from the start**.

## The core ratios

| Ratio | Shape | Where it is used |
|---|---|---|
| **9:16** | Vertical | Reels, Stories, TikTok, Shorts |
| **4:5** | Tall | Instagram and Facebook feed posts |
| **1:1** | Square | Feed, and safe across platforms |
| **16:9** | Wide | YouTube, websites, presentations, TV |
| **2.39:1** | Cinematic | Films and cinematic commercials |

## The practical rule: shoot 16:9 thinking 9:16

Shoot at full resolution (4K where possible) in a wide ratio, but **leave headroom above and below the frame**, keeping the important element in the middle third.

That lets you crop a vertical version without losing the subject. Shooting at a higher resolution than you deliver gives you room to crop without losing quality.

**Better still** — budget permitting — shoot dedicated vertical takes for vertical platforms. Cropping is a rescue, not a first plan.

## The safe zone

Every platform lays its own interface over your video: account name, caption, buttons.

The rule: **leave roughly 15% of the top and bottom of the frame** free of important text. Anything written there disappears behind the app's interface.

## Durations

Ideal durations change as platforms change, so check current limits before delivery. But two things do not change:

**The first three seconds decide the video's fate.** Put your strongest shot at the start, not after a five-second logo sting.

**Shorter usually wins.** A 20-second video watched to the end beats a 60-second one people abandon at second ten.

## Sound: always caption

A large share of social views start with the sound off.

In practice that means:

- Burned-in captions on social cuts, not optional subtitles
- The core message appearing as on-screen text
- A video that is fully understandable without audio

## A short delivery checklist

For every project, ask for:

- 16:9 — full version for the site and YouTube
- 9:16 — short cut for Reels, TikTok and Shorts
- 1:1 or 4:5 — feed version
- A captioned version and a clean one with no text
- High-resolution stills from the shoot

## In short

Ratio is not a decision made in the edit. It is made on set. Teams that think about ratios while framing deliver five versions from one shoot.
