Video is one of the most expensive marketing line items, and the one clients regret most often. You pay a large sum once, and after delivery you discover the work is not what you pictured. The problem is usually not the camera work. It is the choice of partner, made before any camera was switched on.

Here are five practical criteria that separate a smooth project from a troubled one.

## 1. Ask for work like yours, not their best work

Every production house has an impressive showreel. A showreel is built to impress: it is the best few seconds from dozens of projects.

Ask instead for **one complete project, start to finish**, in a field close to yours. If you need a product commercial, a beautiful documentary tells you nothing about their ability to sell your product in thirty seconds.

Also ask what the brief was, and whether it worked. A company that tracks the results of its work thinks differently from one that delivers and moves on.

## 2. Know exactly who will do your project

Many companies sell with one team and deliver with another. The creative director attends the pitch, then the project goes to a team you never met.

Ask directly: who directs? Who shoots? Who edits? And ask for work by **those specific people**. The director makes the difference, not the company name.

## 3. Read the quote as a plan, not a price

A quote with one big number is a warning sign. A good quote states:

- How many shoot days, and where
- Crew size and roles
- How many revision rounds are included
- Which formats and versions you receive
- What counts as an extra cost, and how it is calculated

Revision rounds in particular cause most disputes. Get that number in writing before you sign.

## 4. Ask about ownership and raw files

Most clients overlook this and discover it a year later, when they need a small edit.

Establish clearly:

- Do you own full rights to the final work?
- Do you receive the raw footage and edit projects?
- Is the music licensed to you or to them? For how long?
- If you want to re-cut the video next year, can you, without going back to them?

## 5. Test how they communicate before you commit

The shoot is one day. Managing the project takes weeks. A company that is slow to answer while you are still a prospect will not improve after the first payment.

Watch during the pitch: do they ask you questions, or simply agree to everything? A good partner pushes back sometimes, because they understand the result is their responsibility too.

## In short

Before signing, make sure you know: who executes, what exactly you receive, how many revisions you get, and who owns the result. Four questions that prevent most of what goes wrong later.
