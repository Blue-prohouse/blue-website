Most projects that go wrong do not go wrong on the shoot. They go wrong in the first meeting. Both sides leave imagining a different film, and only discover it when the first cut arrives.

The creative brief is the document that prevents this. One or two pages, written before any work starts, saving weeks of revisions.

## What a brief must contain

### 1. The objective — one measurable sentence

Not "we want a video that introduces the company", but:

> "We want a site visitor to understand what we offer within 60 seconds and click Request a Quote."

The difference is that the second can be judged. More importantly: **one objective**. A video that tries to introduce, sell and recruit at once achieves none of them.

### 2. The audience — a person, not a segment

"Business people in Saudi Arabia" is not an audience. This is closer:

> "A marketing manager at a mid-size company, 30–45, who has seen three competitor pitches and needs something that convinces their CFO."

The narrower the description, the clearer the language, tone and examples become.

### 3. The single message

What is the one sentence you want the viewer to repeat after watching?

Write it in your own words. If you cannot compress it into a line, the thinking is not finished, and filming will not finish it.

### 4. What you do not want

This is the most neglected item, and the one that saves the most time.

State plainly: tones that do not suit you, competitor work you do not want to resemble, clichés you reject, colours outside your identity, any cultural or regulatory sensitivity to avoid.

### 5. Visual references

Three to five pieces you like, **each with the reason you like it**.

"I like this" is not useful. "I like the editing rhythm in the first ten seconds" is very useful. A reference without a reason is usually misread.

### 6. Mandatories

Things that must appear no matter what: the logo and its placement, a specific tagline, a particular product, a regulatory disclaimer, a partner or sponsor name.

Mention them early. Discovering them late means rebuilding whole scenes.

### 7. Deliverables

Do not just say "a video". Specify:

- The main version and its duration
- Short cuts and their ratios (9:16, 1:1, 16:9)
- A subtitled version and a clean one
- A silent version that works without sound
- Stills pulled from the shoot

Defining this upfront is far cheaper than requesting it after delivery.

### 8. Timeline, budget and final approver

A launch date, not "as soon as possible". And a budget range, not a secret figure — a range lets the team propose what fits it.

Most importantly: **who gives final approval?** A project reviewed by five people with no single decision-maker never ends.

